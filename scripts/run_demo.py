"""Runs the assessment's demonstration requests live and writes docs/DEMO.md.

Usage: uv run python scripts/run_demo.py [--keyword-only]
The output records which interpreter ran and when, because eSchool's data changes.
"""

import argparse
from datetime import UTC, datetime
from pathlib import Path

from eschool_assistant.factory import build_assistant
from eschool_assistant.render import render_markdown

EXAMPLES = [
    (
        "1. Clearly specified criteria",
        [
            (
                "A mixed day primary school in Nakawa Division, Kampala, "
                "charging no more than UGX 3 million per term."
            ),
        ],
    ),
    (
        "2. Missing or ambiguous information",
        [
            "I need a good affordable school for my child.",
            "An affordable secondary school in Jinja.",
        ],
    ),
    (
        "3. No suitable results",
        [
            "A boys' boarding secondary school in Gulu under UGX 500,000 per term.",
            "A primary school in Kitgum.",
        ],
    ),
    (
        "4. The assessment's example request",
        [
            (
                "I'm looking for a girls' boarding school in Kampala, preferably around Central "
                "Division, charging no more than UGX 1 million per term and currently admitting "
                "Senior One students."
            ),
        ],
    ),
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keyword-only", action="store_true")
    parser.add_argument("--output", type=Path, default=Path("docs/DEMO.md"))
    args = parser.parse_args()

    assistant = build_assistant(offline_interpreter=args.keyword_only)
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    sections = [
        "# Demonstration\n",
        (
            f"Generated by `scripts/run_demo.py` on {generated} against live eschool.ug. "
            "School data and result counts will change over time. Symbols: ✓ met, "
            "~ partly met, ? unconfirmed, ✗ not met.\n"
        ),
    ]
    if args.keyword_only:
        sections.append(
            "> These outputs used the keyword fallback, not Gemini. Search, verification and "
            "explanations are the production code path. Run the script with `GEMINI_API_KEY` "
            "set to regenerate this file through Gemini.\n"
        )
    for title, queries in EXAMPLES:
        sections.append(f"## {title}\n")
        for query in queries:
            print(f"Running: {query}", flush=True)
            sections.append(render_markdown(assistant.handle(query)))
            sections.append("---\n")
    args.output.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
